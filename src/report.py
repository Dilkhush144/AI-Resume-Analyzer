from datetime import datetime
from typing import Any, Dict, List


def build_report(
    match_score: float,
    gap_data: Dict[str, List[str]],
    ats_issues: List[Dict[str, Any]],
    filename: str = "Resume.pdf"
) -> str:
    """
    Generates a structured, recruiter-ready text report summarizing ATS score, skill gaps, and audit findings.
    """
    score_pct = round(match_score * 100, 1)
    
    if score_pct >= 80:
        fit_tier = "Excellent Match (High Interview Probability)"
    elif score_pct >= 65:
        fit_tier = "Good Match (Minor Skill Alignment Needed)"
    elif score_pct >= 50:
        fit_tier = "Moderate Fit (Key Requirements Missing)"
    else:
        fit_tier = "Low Fit (Significant Tailoring Needed)"

    timestamp = datetime.now().strftime("%Y-%m-%d %H:%M:%S")

    lines = [
        "==================================================================",
        "                 AI RESUME ANALYZER AUDIT REPORT                  ",
        "==================================================================",
        f"Analyzed File  : {filename}",
        f"Generated At   : {timestamp}",
        f"Match Score    : {score_pct} / 100",
        f"Alignment Tier : {fit_tier}",
        "Engine         : Sentence-Transformers (all-MiniLM-L6-v2) + Cosine Similarity",
        "Author         : Dilkhush Raj (https://github.com/Dilkhush144)",
        "------------------------------------------------------------------",
        "",
        "1. TECHNICAL SKILL ALIGNMENT",
        "----------------------------",
    ]

    matched = gap_data.get("matched_skills", [])
    missing = gap_data.get("missing_skills", [])
    general = gap_data.get("general_gaps", [])

    lines.append(f"  • Matched Skills ({len(matched)}):")
    if matched:
        lines.append("    " + ", ".join(s.upper() for s in matched))
    else:
        lines.append("    None detected. Ensure your technical skills are explicitly spelled out.")

    lines.append("")
    lines.append(f"  • Missing Required Skills ({len(missing)}):")
    if missing:
        lines.append("    " + ", ".join(s.upper() for s in missing))
    else:
        lines.append("    None! All prominent JD technical skills are covered in your resume.")

    if general:
        lines.append("")
        lines.append(f"  • Additional Keyword Opportunities ({len(general)}):")
        lines.append("    " + ", ".join(general[:15]))

    lines.extend([
        "",
        "2. ATS & FORMATTING HYGIENE AUDIT",
        "---------------------------------"
    ])

    if ats_issues:
        for idx, check in enumerate(ats_issues, 1):
            status_icon = "✓" if check["status"] == "pass" else ("⚠" if check["status"] == "warning" else "✕")
            lines.append(f"  [{status_icon}] {check['title']} ({check['category']})")
            lines.append(f"      {check['message']}")
    else:
        lines.append("  No obvious ATS or formatting issues identified.")

    lines.extend([
        "",
        "3. RECOMMENDED ACTION ITEMS",
        "---------------------------",
        "  1. Incorporate missing technical keywords organically into your project bullets.",
        "  2. Structure experience using the Google XYZ formula: Accomplished [X], measured by [Y], by doing [Z].",
        "  3. Save resume with clean hyphen/underscore naming (e.g., 'Dilkhush_Raj_Resume.pdf').",
        "  4. Keep length to 1 page for early-career/internship roles (~400-800 words).",
        "",
        "==================================================================",
        "Report generated by AI Resume Analyzer | Developed by Dilkhush Raj",
        "GitHub: https://github.com/Dilkhush144/AI-Resume-Analyzer",
        "=================================================================="
    ])

    return "\n".join(lines)
